/**
 * Returns all built-in device presets.
 * Custom devices are stored separately in settings and merged at runtime.
 */
export function getDevicePresets(): DevicePreset[] {
  return DEVICE_PRESETS
}

/**
 * Looks up a preset by ID from the combined canonical + custom list.
 */
export function findPreset(id: string, customDevices: DevicePreset[] = []): DevicePreset | undefined {
  return [...DEVICE_PRESETS, ...customDevices].find((d) => d.id === id)
}

